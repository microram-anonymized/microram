"""Campaign summary loader (the input of `plot`): no clock reads, workers, or measurements."""
import copy
import json
from pathlib import Path
import tempfile
import unittest

from analysis.oram_bench.reduction import SUMMARY_SCHEMA_VERSION, load_campaign_summary


def fixture():
    spec = {"requested_capacity": 16, "arrival": "fixed"}
    row = {"trial_id": "trial-a", "attempt_id": "attempt-a",
           "environment_class": "synthetic", "runtime": "fake", "build_identity": "sha256-" + "a" * 64,
           "spec": {**spec, "repetition": 0, "workload_seed": 1, "arrival_seed": 2},
           "summary": {"response": {"p99_ns": 123, "p999_ns": None},
                       "drained_ops_per_second": 0}, "publication_validated": False, "memory": None,
           "queue_stability": "stable", "publication_blockers": ["cycle_coverage_unknown"]}
    return {"campaign_summary_schema_version": SUMMARY_SCHEMA_VERSION, "plan_id": "plan-a",
            "campaign": {"name": "fixture", "plan_id": "plan-a", "worker_sha256": "sha256-" + "a" * 64,
                         "library_header_sha256": None},
            "trial_status": {"counts": {"complete": 1, "failed": 1, "skipped": 1}},
            "groups": [{"group_id": "group-a", "environment_class": "synthetic",
                        "runtime": "fake", "build_identity": "sha256-" + "a" * 64, "spec": spec,
                        "security": "not_oblivious", "key_layout": "permuted", "stored_value_bytes": 8,
                        "throughput": {"median": 0}, "repetitions": [row]}]}


class SummaryLoaderTests(unittest.TestCase):
    def load(self, document):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "summary.json"
            path.write_text(json.dumps(document))
            return load_campaign_summary(path)

    def test_preserves_evidence_and_nulls(self):
        original = fixture()
        loaded = self.load(original)
        self.assertEqual(loaded, original)
        self.assertEqual(loaded["trial_status"]["counts"]["failed"], 1)

    def test_rejects_mixed_or_duplicate_repetitions(self):
        for field, value in (("environment_class", "different"), ("runtime", "native"),
                             ("build_identity", "sha256-" + "b" * 64), ("spec", {"requested_capacity": 32})):
            document = fixture()
            document["groups"][0]["repetitions"][0][field] = value
            with self.assertRaises(ValueError):
                self.load(document)
        document = fixture()
        document["groups"][0]["repetitions"] *= 2
        with self.assertRaises(ValueError):
            self.load(document)
        document = fixture()
        document["groups"].append(copy.deepcopy(document["groups"][0]))
        with self.assertRaises(ValueError):
            self.load(document)

    def test_schema_and_empty_campaign(self):
        # Only the current schema version loads; other summaries must be regenerated by reduce.
        for version in (True, 0, 1, 2, 3, 4, 5, 7, "6"):
            document = fixture()
            document["campaign_summary_schema_version"] = version
            with self.subTest(version=version), self.assertRaisesRegex(ValueError, "re-run reduce"):
                self.load(document)
        for campaign in (None, {"plan_id": "plan-a", "worker_sha256": None},
                         {"name": "fixture", "plan_id": "plan-b", "worker_sha256": None},
                         {"name": "fixture", "plan_id": "plan-a"}):
            document = fixture()
            document["campaign"] = campaign
            with self.subTest(campaign=campaign), self.assertRaisesRegex(ValueError, "campaign name"):
                self.load(document)
        document = fixture()
        document["groups"] = []
        self.assertEqual(self.load(document)["groups"], [])


if __name__ == "__main__":
    unittest.main()
