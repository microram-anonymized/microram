"""Independently certify the checked-in stage table's Poisson inequalities.

The table is src/oram/rebuild/cpu_byteslice_stash_capacity_table.hpp,
generated by gen_stash_capacity_table.cpp and consumed by the rebuild's
per-level stash sizing (LevelStashSlots).

This does not justify a production stage's distribution or lifetime count.
A float search proposes a rational Chernoff parameter; directed interval
arithmetic, including a positive omitted-tail bound, decides acceptance.
No generated header or production capacity is changed by this tool.
"""

from decimal import Decimal
from math import exp
from pathlib import Path
import re

from gen_residual_tier_bound import log_interval, poisson_mgf
from residual_occupancy_certificate import interval

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "src/oram/rebuild/cpu_byteslice_stash_capacity_table.hpp"


def entries(path=HEADER):
    source = path.read_text()
    first = int(re.search(r"kStashCapMinExp = (\d+)", source)[1])
    last = int(re.search(r"kStashCapMaxExp = (\d+)", source)[1])
    depths = int(re.search(r"kStashCapMaxBuckets = (\d+)", source)[1])
    table = source.split(" = {", 1)[1].split("};", 1)[0]
    values = [int(x) for x in re.findall(r"(\d+)ull", table)]
    width = last - first + 1
    if len(values) != depths * width:
        raise ValueError("unexpected capacity table shape")
    return [(64 * (i // width + 1), first + i % width, n)
            for i, n in enumerate(values)]


def propose_z(outputs, slots):
    # Derivative with respect to log(z) of the Poisson excess log MGF.
    # This float calculation is only a search, never evidence of acceptance.
    def tilted_mean(z):
        point = exp(-32)
        for k in range(1, 65):
            point *= 32 / k
        power, delta, moment = 1.0, 0.0, 0.0
        for k in range(65, 257):
            point *= 32 / k
            power *= z
            delta += point * (power - 1)
            moment += (k - 64) * point * power
        return moment / (1 + delta)

    low, high = 1.0, 3.5
    for _ in range(50):
        mid = (low + high) / 2
        if outputs * tilted_mean(mid) < slots + 1:
            low = mid
        else:
            high = mid
    denominator = 1 << 24
    numerator = max(denominator+1, round((low + high) / 2 * denominator))
    return interval(numerator) / denominator


def certify(outputs, slots, exponent, z=None, mean=32):
    if outputs < 1 or slots < 1 or exponent < 1:
        raise ValueError("positive outputs, slots and exponent required")
    z = propose_z(outputs, slots) if z is None else interval(z)
    if z.low <= 1 or z.high > 4:
        raise ValueError("certificate supports 1 < z <= 4")
    upper_log2 = ((log_interval(poisson_mgf(z, mean)) * outputs -
                   log_interval(z) * (slots + 1)) /
                  log_interval(interval(2))).high
    return upper_log2 <= -exponent, upper_log2


def main():
    failed, checked, zero = [], 0, 0
    slack = Decimal("Infinity")
    tightest = None
    for slots, exponent, outputs in entries():
        if outputs == 0:
            # Zero is a rejection sentinel for all nonempty networks.
            zero += 1
            continue
        ok, bound = certify(outputs, slots, exponent)
        checked += 1
        margin = -Decimal(exponent) - bound
        if margin < slack:
            slack, tightest = margin, (slots, exponent, outputs)
        if not ok:
            failed.append((slots, exponent, outputs, str(bound)))
    print(f"Certified {checked-len(failed)}/{checked} positive thresholds; "
          f"{zero} zero sentinels")
    print(f"Minimum certified slack in bits: {slack}; cell={tightest}")
    for failure in failed:
        print("UNCERTIFIED", failure)
    raise SystemExit(bool(failed))


if __name__ == "__main__":
    main()
