"""Generate conservative integer Chernoff coefficients for residual tiers.

Run from the repository root. No floating-point optimization or unbounded
tail truncation enters the certificate.

The output, src/oram/rebuild/cpu_byteslice_residual_tier_bound.hpp, holds
fixed-point (2^48) enclosures of log2(z) and log2 E[z^((Poisson(32)-64)+)]
for z = 33/32 .. 128/32. Its ResidualTierBuckets() picks, by a Chernoff
bound in integer arithmetic, the smallest residual tier depth (1..8 buckets)
whose half-load occupancy excess exceeds the tier with probability at most
2^-exponent; the rebuild geometry uses it to size every level's residual
tier for a lifetime of accesses. Running this file rewrites that header;
tests/analysis/test_residual_tier_bound.py checks it is current. The bound
assumes independent uniform destinations at a load of at most 32 records
per bucket; analysis/bound_certification/REPORT.tex states how it is
applied to each packing operation. After regeneration, run analysis/modulo_occupancy_certificate.py as well:
the selected capacities' coverage of biased maps is checked separately.
"""

from decimal import ROUND_FLOOR, ROUND_CEILING
from pathlib import Path

from residual_occupancy_certificate import interval, Interval, DOWN, UP

SCALE = 1 << 48


def log_interval(x):
    # Decimal.ln is correctly rounded to nearest, regardless of the context's
    # rounding mode. One adjacent representable value encloses the exact log.
    return Interval(DOWN.next_minus(DOWN.ln(x.low)),
                    UP.next_plus(UP.ln(x.high)))


def poisson_mgf(z, mean=32):
    """Upper envelope for the excess MGF, with a positive omitted tail.

    The returned high endpoint bounds the MGF; the low endpoint need not
    bound the true MGF from below (the normalization itself is an upper
    bound). The default preserves the generated half-load coefficients.
    """
    z, mean = interval(z), interval(mean)
    if z.low <= 1 or mean.low <= 0:
        raise ValueError("require z > 1 and positive mean")
    # Positive partial sum <= exp(mean), so its reciprocal bounds exp(-mean).
    term, exp_lower = interval(1), interval(1)
    for k in range(1, 257):
        term = term * mean / k
        exp_lower = exp_lower + term
    point = interval(1) / interval(exp_lower.low)
    for k in range(1, 65):
        point = point * mean / k
    power, delta = interval(1), interval(0)
    for k in range(65, 257):
        point = point * mean / k
        power = power * z
        delta = delta + point * (power - 1)
    ratio = z * mean / 257
    if ratio.high >= 1:
        raise ValueError("increase the cutoff for this mean/z")
    delta = delta + point * power * ratio / (interval(1) - ratio)
    return interval(1) + delta


def coefficients():
    ln2 = log_interval(interval(2))
    for numerator in range(33, 129):
        z = interval(numerator) / 32
        a = ((log_interval(z) / ln2) * SCALE).low
        b = ((log_interval(poisson_mgf(z)) / ln2) * SCALE).high
        yield (int(a.to_integral_value(rounding=ROUND_FLOOR)),
               int(b.to_integral_value(rounding=ROUND_CEILING)))


def render():
    rows = "\n".join(f"    {{{a}ull, {b}ull}}," for a, b in coefficients())
    return """#pragma once

// GENERATED by analysis/gen_residual_tier_bound.py; do not edit by hand.
// For z = 33/32, ..., 128/32, these enclose log2(z) from below and
// log2(E[z^((Poisson(32)-64)+)]) from above, scaled by 2^48.
// analysis/bound_certification/REPORT.tex states the assumptions needed to
// apply this occupancy bound to a rebuild.

#include <cstdint>

namespace microram {
namespace byteslice {

struct ResidualTierChernoffCoefficient {
  uint64_t log_z_lower;
  uint64_t log_mgf_upper;
};
inline constexpr ResidualTierChernoffCoefficient kResidualTierChernoff[] = {
""" + rows + """
};

// Smallest supported tier whose half-load multinomial occupancy excess
// exceeds its capacity with probability at most 2^-exponent. Returns zero
// when the coefficient grid cannot certify a depth of at most eight buckets.
// The comparison uses integer arithmetic only; all products fit in 128 bits.
inline unsigned ResidualTierBuckets(uint64_t buckets, unsigned exponent) {
  using Wide = unsigned __int128;
  unsigned best = 0;
  for (const auto& c : kResidualTierChernoff) {
    const Wide rhs = Wide{buckets} * c.log_mgf_upper +
                     (Wide{exponent} << 48);
    const Wide denominator = Wide{64} * c.log_z_lower;
    const Wide depth = rhs <= c.log_z_lower ? 1 :
        (rhs - c.log_z_lower + denominator - 1) / denominator;
    const unsigned candidate = depth < 1 ? 1 : depth > 8 ? 0 :
        static_cast<unsigned>(depth);
    if (candidate != 0 && (best == 0 || candidate < best)) best = candidate;
  }
  return best;
}

}  // namespace byteslice
}  // namespace microram
"""


if __name__ == "__main__":
    target = Path(__file__).resolve().parents[1] / (
        "src/oram/rebuild/cpu_byteslice_residual_tier_bound.hpp")
    target.write_text(render())
