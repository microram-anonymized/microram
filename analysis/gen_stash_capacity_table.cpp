// Offline generator for the per-butterfly-level residual stash capacity table.
//
// Sizing the per-level residual stashes of a butterfly rebuild needs a
// Poisson(32) Chernoff bound.  That numerical work is design-time only: this
// tool precomputes it once and emits a hardcoded integer table
// (src/oram/rebuild/cpu_byteslice_stash_capacity_table.hpp, consumed through
// LevelStashSlots) that the runtime looks up in O(1), so no floating-point
// bound calculation runs when the ORAM is built.
//
// Regenerate (from the repo root):
//   g++ -O2 -std=c++17 analysis/gen_stash_capacity_table.cpp -o gen_table
//   ./gen_table > src/oram/rebuild/cpu_byteslice_stash_capacity_table.hpp
//
// Model (src/oram/rebuild/DESIGN.md describes the rebuild): one butterfly
// level of N output buckets, each ~Poisson(32), O = max(X - 64, 0).  For a
// stash of S slots,  P[level overflow >= S+1] <= min_z z^-(S+1) E[z^O]^N.  The
// table stores, for each stash size s*64 and each failure exponent e, the
// largest N whose bound is <= 2^-e. This float generator only proposes the
// thresholds. After regeneration, certify every positive entry with:
//   python3 analysis/stash_capacity_certificate.py
//   python3 analysis/modulo_occupancy_certificate.py
// These checkers use directed arithmetic and an explicit omitted-tail bound;
// rounding a requested exponent up is not itself a numerical certificate.

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <limits>
#include <vector>

namespace {

constexpr int kMean = 32;
constexpr int kCap = 64;
constexpr int kXMax = 512;
constexpr int kMinExp = 64;
constexpr int kMaxExp = 200;
constexpr unsigned kMaxBuckets = 8;

std::vector<double> g_logz;
std::vector<double> g_log_ez;

void BuildGrid() {
  std::vector<double> pmf(kXMax + 1);
  double v = std::exp(-static_cast<double>(kMean));
  pmf[0] = v;
  for (int x = 1; x <= kXMax; ++x) {
    v *= static_cast<double>(kMean) / x;
    pmf[x] = v;
  }
  double head = 0.0;
  for (int x = 0; x <= kCap; ++x) head += pmf[x];
  for (double z = 1.04; z <= 3.5; z += 0.02) {
    double ez = head;
    double zp = 1.0;
    for (int x = kCap + 1; x <= kXMax; ++x) {
      zp *= z;
      ez += pmf[x] * zp;
    }
    g_logz.push_back(std::log2(z));
    g_log_ez.push_back(std::log2(ez));
  }
}

// log2 upper bound on P[sum over N Poisson(32) buckets of max(X-64,0) >= S+1].
double ChernoffLog2(double n_events, unsigned stash_slots) {
  double best = std::numeric_limits<double>::infinity();
  for (size_t i = 0; i < g_logz.size(); ++i) {
    const double b =
        -(static_cast<double>(stash_slots) + 1.0) * g_logz[i] +
        n_events * g_log_ez[i];
    if (b < best) best = b;
  }
  return best;
}

// Largest integer N with ChernoffLog2(N, stash_slots) <= -e (the bound is
// monotone increasing in N).
uint64_t MaxEvents(unsigned stash_slots, int e) {
  const double target = -static_cast<double>(e);
  if (ChernoffLog2(0.0, stash_slots) > target) return 0;
  double lo = 0.0;
  double hi = 1e18;
  if (ChernoffLog2(hi, stash_slots) <= target) return static_cast<uint64_t>(hi);
  for (int it = 0; it < 200 && hi - lo > 0.5; ++it) {
    const double mid = 0.5 * (lo + hi);
    if (ChernoffLog2(mid, stash_slots) <= target) {
      lo = mid;
    } else {
      hi = mid;
    }
  }
  return static_cast<uint64_t>(lo);
}

}  // namespace

int main() {
  BuildGrid();
  const int cols = kMaxExp - kMinExp + 1;
  std::printf("#pragma once\n\n");
  std::printf(
      "// GENERATED by analysis/gen_stash_capacity_table.cpp -- do not edit by "
      "hand.\n");
  std::printf(
      "// kStashCapMaxEvents[s-1][e-kStashCapMinExp] = the largest number of\n"
      "// output-bucket events N for which a per-level stash of s*64 slots\n"
      "// keeps one butterfly level's overflow probability <= 2^-e\n"
      "// (Poisson(32), Chernoff).  Consumed by LevelStashSlots below.\n\n");
  std::printf("#include <cmath>\n#include <cstdint>\n\n");
  std::printf("namespace microram {\nnamespace byteslice {\n\n");
  std::printf("inline constexpr int kStashCapMinExp = %d;\n", kMinExp);
  std::printf("inline constexpr int kStashCapMaxExp = %d;\n", kMaxExp);
  std::printf("inline constexpr unsigned kStashCapMaxBuckets = %u;\n\n",
              kMaxBuckets);
  std::printf(
      "inline constexpr uint64_t kStashCapMaxEvents[kStashCapMaxBuckets][%d] = "
      "{\n",
      cols);
  for (unsigned s = 1; s <= kMaxBuckets; ++s) {
    std::printf("    {");
    for (int e = kMinExp; e <= kMaxExp; ++e) {
      if (((e - kMinExp) % 8) == 0) std::printf("\n     ");
      std::printf("%lluull%s", static_cast<unsigned long long>(MaxEvents(s * 64, e)),
                  e < kMaxExp ? ", " : "");
    }
    std::printf("},\n");
  }
  std::printf("};\n\n");
  std::printf(
      "// Smallest per-level stash (a multiple of 64 slots) whose single-level\n"
      "// overflow bound is <= target_log2 (<= 0).  Returns 0 if none in range.\n"
      "inline unsigned LevelStashSlots(double n_events, double target_log2) {\n"
      "  const double strict = -target_log2;\n"
      "  int e = static_cast<int>(strict);\n"
      "  if (strict > static_cast<double>(e)) ++e;  // ceil: round to stricter\n"
      "  if (e < kStashCapMinExp) e = kStashCapMinExp;\n"
      "  if (e > kStashCapMaxExp) return 0;  // lifetime too strict for the "
      "table\n"
      "  const uint64_t need = static_cast<uint64_t>(std::ceil(n_events));\n"
      "  const int col = e - kStashCapMinExp;\n"
      "  for (unsigned s = 1; s <= kStashCapMaxBuckets; ++s) {\n"
      "    if (need <= kStashCapMaxEvents[s - 1][col]) return s * 64u;\n"
      "  }\n"
      "  return 0;\n"
      "}\n\n");
  std::printf("}  // namespace byteslice\n}  // namespace microram\n");
  return 0;
}
