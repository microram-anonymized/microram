IMPORT = re.compile(r"^\s*(?:(?:public|private|meta)\s+)?import\s+(?:all\s+)?"
                    r"([A-Za-z0-9_.]+)\s*$", re.MULTILINE)


def scan(lean_dir, roots):
    """Follow explicit project imports; fail on missing sources, keep foundations external."""
    sources = {}

    def source(module):
        if module not in sources:
            path = lean_dir / (module.replace(".", "/") + ".lean")
            raw = path.read_bytes()
            code = strip_comments(raw.decode())
            imports = IMPORT.findall(code)
            # Fail if a future header form would otherwise silently omit an edge.
            for line in code.splitlines():
                if re.match(r"^\s*(?:(?:public|private|meta)\s+)?import\b", line):
                    if not IMPORT.fullmatch(line):
                        raise ValueError(f"unsupported import syntax in {path}: {line}")
            olean = lean_dir / ".lake/build/lib/lean" / (module.replace(".", "/") + ".olean")
            sources[module] = {
                "imports": imports,
                "source_bytes": len(raw),
                "source_sha256": hashlib.sha256(raw).hexdigest(),
                "olean_bytes": olean.stat().st_size if olean.is_file() else None,
                # Existing generated certificate matrices use Tab* modules;
                # Table.lean contains ordinary proofs, not generated data.
                "matrix": (module.rsplit(".", 1)[-1].startswith("Tab")
                           and "Generated by" in raw[:256].decode(errors="replace")),
            }
        return sources[module]

    result = {}
    for root in roots:
        seen, external, pending = set(), set(), [root]
        while pending:
            module = pending.pop()
            if module in seen:
                continue
            seen.add(module)
            for imported in source(module)["imports"]:
                if imported == "RebuildBound" or imported.startswith("RebuildBound."):
                    pending.append(imported)
                else:
                    external.add(imported)
        modules = sorted(seen)
        matrices = [m for m in modules if source(m)["matrix"]]
        missing = [m for m in modules if source(m)["olean_bytes"] is None]
        result[root] = {
            "module_count": len(modules),
            "source_bytes": sum(source(m)["source_bytes"] for m in modules),
            "available_olean_bytes": sum(source(m)["olean_bytes"] or 0 for m in modules),
            "missing_oleans": missing,
            "matrix_module_count": len(matrices),
            "matrix_source_bytes": sum(source(m)["source_bytes"] for m in matrices),
            "matrix_olean_bytes": sum(source(m)["olean_bytes"] or 0 for m in matrices),
            "source_closure_sha256": hashlib.sha256("\n".join(
                m + " " + source(m)["source_sha256"] for m in modules).encode()).hexdigest(),
            "modules": modules,
            "direct_external_imports": sorted(external),
        }
    return result

