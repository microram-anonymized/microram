#!/usr/bin/env python3
"""Driver: compare model_tp.py with the engine on every fixture of a directory
and print / write the match counts, the breakdown and the coverage counters.

    run_tp.py [DIR] [--assert-dir DIR2] [--results FILE]

With --assert-dir, the fixtures of the same names in DIR2 (generated by the
asserts-on binary) must be byte-identical to DIR's.
"""
import argparse, glob, json, os, sys
from collections import Counter
from multiprocessing import Pool

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
WORK = os.path.abspath(os.environ.get(
    'ORACLE_TP_WORK', os.path.join(HERE, '..', '..', '.lake', 'oracle', 'fixtures-tp')))
sys.path.insert(0, HERE)
import model_tp as m


def one(path):
    f = m.load(path)
    ok, detail, res = m.compare(f)
    g = f['geometry']
    out = f['outputs']
    return {
        'file': os.path.basename(path), 'ok': ok, 'detail': detail,
        'fmt': f['format'], 'D': g['D'], 'T': g['T'], 'S': g['stage_stash_buckets'],
        'tb': g['a_tier_pages'], 'out_tier': g['out_tier_pages'], 'r_pages': g['r_pages'],
        'rho': g['range_bits'], 'I': g['range_index_bits'], 'dfs': g['dfs'],
        'verdict': out['verdict'], 'kind': out['kind'],
        'n_main': len(out['main']),
        'n_tier': len(out['R'] if f['format'] == 'top-prep-fixture/0' else out['tier']),
        'counters': dict(res.counters),
        'n_in': (len(f['inputs']['A_main']) + len(f['inputs']['A_tier'])
                 if f['format'] == 'top-prep-fixture/0' else len(f['input'])),
    }


def block(title, rows, lines):
    n = len(rows)
    ok = sum(r['ok'] for r in rows)
    succ = [r for r in rows if r['verdict'] == 'success']
    fail = [r for r in rows if r['verdict'] == 'failure']
    lines.append('== %s ==' % title)
    lines.append('fixtures: %d   model == engine: %d   mismatches: %d' % (n, ok, n - ok))
    lines.append('lane-exact on success: %d/%d   verdict+kind on failure: %d/%d' % (
        sum(r['ok'] for r in succ), len(succ), sum(r['ok'] for r in fail), len(fail)))
    lines.append('failure kinds: %s' % dict(Counter(r['kind'] for r in fail)))
    lines.append('\nby D (fixtures / success / failures):')
    for D in (1, 2, 4, 8):
        rs = [r for r in rows if r['D'] == D]
        lines.append('  D=%d  %4d  %4d  %4d   failures by kind: %s' % (
            D, len(rs), sum(r['verdict'] == 'success' for r in rs),
            sum(r['verdict'] == 'failure' for r in rs),
            dict(Counter(r['kind'] for r in rs if r['verdict'] == 'failure'))))
    lines.append('\nby T (fixtures / success / failures):')
    for T in sorted({r['T'] for r in rows}):
        rs = [r for r in rows if r['T'] == T]
        lines.append('  T=%-5d %4d  %4d  %4d   %s' % (
            T, len(rs), sum(r['verdict'] == 'success' for r in rs),
            sum(r['verdict'] == 'failure' for r in rs),
            dict(Counter(r['kind'] for r in rs if r['verdict'] == 'failure'))))
    lines.append('\nby S (stage-stash pages) and tier width:')
    for key in sorted({(r['S'], r['tb'], r['out_tier']) for r in rows}):
        rs = [r for r in rows if (r['S'], r['tb'], r['out_tier']) == key]
        lines.append('  S=%d  A-tier pages=%d  published-tier pages=%d: %d fixtures, failures %s' % (
            key[0], key[1], key[2], len(rs),
            dict(Counter(r['kind'] for r in rs if r['verdict'] == 'failure'))))
    lines.append('\nrange plans (T, D, rho, I, dfs): fixtures')
    for k, v in sorted(Counter((r['T'], r['D'], r['rho'], r['I'], r['dfs']) for r in rows).items()):
        lines.append('   %s %d' % (k, v))
    cov, cov_s = Counter(), Counter()
    for r in rows:
        for k, v in r['counters'].items():
            if v:
                cov[k] += 1
                if r['verdict'] == 'success':
                    cov_s[k] += 1
    lines.append('\ncoverage: fixtures with a nonzero effect (of %d; counters of a failing run stop at its failure)' % n)
    for k in sorted(cov):
        lines.append('  %-22s %5d   (successful runs: %d)' % (k, cov[k], cov_s[k]))
    lines.append('')


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('directory', nargs='?', default=os.path.join(WORK, 'fx'))
    for flag in ('--assert-dir', '--results', '--engine-dir', '--engine-assert-dir'):
        ap.add_argument(flag)
    ap.add_argument('--jobs', type=int, default=48)
    args = ap.parse_args()
    opts = {'--' + k.replace('_', '-'): v for k, v in vars(args).items() if v is not None}
    d = args.directory
    files = sorted(glob.glob(os.path.join(d, 'p*.json')) + glob.glob(os.path.join(d, 'i*.json')))
    efiles = sorted(glob.glob(os.path.join(opts['--engine-dir'], 'e*.json'))) if '--engine-dir' in opts else []
    if not files or ('--engine-dir' in opts and not efiles):
        ap.error('a requested fixture directory is missing or empty')
    if '--engine-assert-dir' in opts and '--engine-dir' not in opts:
        ap.error('--engine-assert-dir requires --engine-dir')
    with Pool(args.jobs) as pool:
        rows = pool.map(one, files + efiles, chunksize=4)
    lines = []
    prep = [r for r in rows if r['fmt'] == 'top-prep-fixture/0']
    init = [r for r in rows if r['fmt'] == 'top-init-fixture/0' and not r['file'].startswith('e')]
    eng = [r for r in rows if r['file'].startswith('e')]
    block('TOP PREPARATION (top-prep-fixture/0)', prep, lines)
    block('DIRECT INITIALIZATION ROUTE (top-init-fixture/0)', init, lines)
    if eng:
        block('DIRECT INITIALIZATION THROUGH THE PUBLIC ENGINE: LevelArenaEngine::Initialize + read back of the published top', eng, lines)
    n, ok = len(rows), sum(r['ok'] for r in rows)
    lines.append('TOTAL: %d fixtures, model == engine on %d, mismatches %d' % (n, ok, n - ok))
    for r in rows:
        if not r['ok']:
            lines.append('MISMATCH %s %s' % (r['file'], r['detail']))
    builds_match = True
    if '--assert-dir' in opts:
        d2 = opts['--assert-dir']
        same = diff = missing = 0
        for p in files:
            q = os.path.join(d2, os.path.basename(p))
            if not os.path.exists(q):
                missing += 1
            elif open(p, 'rb').read() == open(q, 'rb').read():
                same += 1
            else:
                diff += 1
        lines.append('asserts-on binary (%s): byte-identical %d, different %d, missing %d' % (
            d2, same, diff, missing))
        builds_match = builds_match and diff == 0 and missing == 0
    if '--engine-assert-dir' in opts:
        same = diff = missing = 0
        for p in efiles:
            q = os.path.join(opts['--engine-assert-dir'], os.path.basename(p))
            if not os.path.exists(q):
                missing += 1
            elif open(p, 'rb').read() == open(q, 'rb').read():
                same += 1
            else:
                diff += 1
        lines.append('asserts-on public-engine binary (%s): byte-identical %d, different %d, missing %d' % (
            opts['--engine-assert-dir'], same, diff, missing))
        builds_match = builds_match and diff == 0 and missing == 0
    text = '\n'.join(lines)
    print(text)
    result_path = opts.get('--results', os.path.join(WORK, 'RESULTS.txt'))
    os.makedirs(os.path.dirname(os.path.abspath(result_path)), exist_ok=True)
    with open(result_path, 'w') as fh:
        fh.write(text + '\n')
    with open(os.path.join(d, 'summary.json'), 'w') as fh:
        json.dump({'n': n, 'ok': ok, 'rows': rows}, fh)
    sys.exit(0 if ok == n and builds_match else 1)


if __name__ == '__main__':
    main()
