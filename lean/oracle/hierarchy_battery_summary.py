#!/usr/bin/env python3
"""The hierarchy replay battery's summary, from one run's report.

    python3 oracle/hierarchy_battery_summary.py REPORT.json OUT.txt

REPORT.json is what `oracle/hierarchy_replay_tests.py` writes (`--report`,
default .lake/oracle/hierarchy-report.json); OUT.txt is the summary to
write (`hierarchy_replay_tests.py --summary OUT.txt` calls this script). Every number in the summary is read
from the report (the oracle's lines, the driver's checks and the fixture
facts the driver recorded); nothing is typed in. Exit 1 if the report's run
did not pass. Standard library only; safe under `python3 -I`.
"""

import json
import sys

KIND_ORDER = ("small (scalar)", "small (batch)", "two-secret (scalar)", "two-secret (batch)",
              "selected (scalar)", "selected (batch)")


def n(x):
    return f"{x:,}"


def main():
    if len(sys.argv) != 3:
        print(__doc__.split("\n\n")[1])
        return 2
    with open(sys.argv[1]) as f:
        rep = json.load(f)
    bat = rep["battery"]
    runs = bat["runs"]
    out = []
    w = out.append

    w("Hierarchy replay battery summary")
    w("=" * 32)
    w("")
    w("Generated by oracle/hierarchy_battery_summary.py from the report of one battery run")
    w("(oracle/hierarchy_replay_tests.py). Do not edit by hand.")
    w("")
    w(f"date:     {rep['date']}")
    w(f"commit:   {rep['commit']}" + ("" if rep.get("worktree_clean") else
                                     " (with uncommitted changes under lean/)"))
    w(f"command:  {rep['command']}")
    w(f"result:   {'ALL OK' if rep['all_ok'] else 'SOME CHECKS FAILED'}")
    t = [f"total {rep['total_seconds']} s"]
    if "generation_seconds" in rep:
        t.append(f"fixture generation {rep['generation_seconds']} s")
    t.append(f"oracle on the fixtures {bat['wall_seconds']} s ({bat['processes']} processes)")
    t.append(f"mutations {rep['mutations']['wall_seconds']} s")
    w("timings:  " + ", ".join(t))
    w("")

    # ---- runs --------------------------------------------------------------
    kinds = {}
    for r in runs:
        kinds.setdefault(r["kind"], []).append(r)
    w(f"RUNS: {len(runs)} fixtures, {sum(1 for r in runs if r.get('ok'))} as expected "
      f"({bat['pass_outright']} pass outright; the others fail exactly their deliberate trace-premise "
      f"violations)")
    for k in KIND_ORDER:
        if k in kinds:
            w(f"  {k:20} {len(kinds[k]):3}")
    for k in sorted(set(kinds) - set(KIND_ORDER)):
        w(f"  {k:20} {len(kinds[k]):3}")
    facts = [r["facts"] for r in runs]
    w("  attributes (overlapping): "
      f"eager {sum(1 for f in facts if f['drive'] == 'eager')}, "
      f"lazy {sum(1 for f in facts if f['drive'] == 'lazy')}, "
      f"of which kAuto/kShare {sum(1 for f in facts if f['policy'] == 'auto')}; "
      f"initialized {sum(1 for f in facts if f['initialized'])}; "
      f"forced keys {sum(1 for f in facts if f['forced'])}; "
      f"native capacity failure {sum(1 for f in facts if f['native_failure'])}")
    orig = [r for r in runs if not r["facts"]["two_secret"]
            and r["name"] not in ("j_selected_uniform_batch", "j_selected_half_batch")]
    w(f"  the base battery (without the two-secret and selected batch runs): "
      f"{len(orig)} runs")
    w("")

    # ---- tables ------------------------------------------------------------
    def tsum(rs, k):
        return sum((r.get("line") or {}).get(k) or 0 for r in rs)

    w("TABLES (every published table, lane for lane against the model's)")
    w(f"  all runs: {n(tsum(runs, 'tables'))} tables, {n(tsum(runs, 'compared'))} compared, "
      f"{n(tsum(runs, 'skipped_top'))} skipped, {n(tsum(runs, 'mismatches'))} mismatches")
    for k in KIND_ORDER:
        if k in kinds:
            rs = kinds[k]
            w(f"  {k:20} {n(tsum(rs, 'tables')):>7} tables, {n(tsum(rs, 'compared')):>7} compared, "
              f"{tsum(rs, 'skipped_top'):3} skipped")
    w(f"  the base battery ({len(orig)} runs): {n(tsum(orig, 'tables'))} tables, "
      f"{n(tsum(orig, 'compared'))} compared, {tsum(orig, 'skipped_top')} skipped")
    w("  skipped = the top's tables of the selected runs (the replay does not evaluate a top of "
      "2^22 buckets); compared = tables - skipped on every run (checked)")
    w("")

    # ---- selected ----------------------------------------------------------
    w("SELECTED CONFIGURATIONS: levels with tables published during the run (tables per level)")
    for r in runs:
        f = r["facts"]
        if f["selected"]:
            L = f["levels"]
            below = {int(l): c for l, c in f["tables_by_level"].items() if int(l) < L}
            w(f"  {r['name']:26} {f['selected']:7} L = {L}: levels {min(below)}-{max(below)} "
              f"({', '.join(f'{l}: {c}' for l, c in sorted(below.items()))}); top: "
              f"{f['tables_by_level'].get(str(L), 0)} tables (the empty top and the initialized top, "
              f"skipped); {n(f['accesses'])} accesses, {f['prefixes']} level-one ordinals")
    w("  levels above these publish nothing in a 70,000-access run; they are covered only by the "
      "shapes check (below)")
    w("")

    # ---- view --------------------------------------------------------------
    vt = bat["view_totals"]
    w("ADVERSARY'S VIEW (touched bucket and real/dummy flag of every plan entry, both engines)")
    w("  per kind: probing operations (slots), plan entries, real entries; arena | synchronous")
    for k in KIND_ORDER:
        if k not in vt:
            continue
        v = vt[k]
        line = (f"  {k:20} {v['fixtures']:2} runs: arena {n(v['arena_accesses'])} / {n(v['arena_entries'])} / "
                f"{n(v['arena_real'])} | sync {n(v['sync_accesses'])} / {n(v['sync_entries'])} / "
                f"{n(v['sync_real'])}; {v['mismatches']} mismatches")
        w(line)
        extra = []
        if v["chunks"]:
            extra.append(f"chunks {n(v['chunks'])} (both engines), chunk lanes {n(v['chunk_lanes'])}, "
                         f"duplicate lanes {n(v['arena_duplicate_lanes'])} + {n(v['sync_duplicate_lanes'])}")
        if v["arena_top_entries"] and k.startswith("selected"):
            extra.append(f"top entries compared {n(v['arena_top_entries'])} + {n(v['sync_top_entries'])} "
                         f"(the top's contents not evaluated: each is its plan's last entry)")
        extra.append(f"{n(v['sync_compared'])} synchronous plans equal to syncSchedule, {n(v['units'])} "
                     f"prefixes reproduced by traceOf, BatchScalar on {v['scalar_batch_checked']} scalar views")
        for e in extra:
            w(f"  {'':20}   {e}")
    tot = {key: sum(v[key] for v in vt.values()) for key in next(iter(vt.values()))}
    w(f"  all runs: arena {n(tot['arena_entries'])}, sync {n(tot['sync_entries'])} plan entries, "
      f"{tot['mismatches']} mismatches")
    w("")

    # ---- trace premises ----------------------------------------------------
    w("TRACE PREMISES (TracePremises at N = config.key_bound = 32 T, every run)")
    bad = [r for r in runs if (r.get("trace_premises") or {}).get("result") != "pass"]
    w(f"  pass on {len(runs) - len(bad)} of {len(runs)} runs; the others fail only trace_premises.keys, "
      f"deliberately:")
    for r in bad:
        keys = r["trace_premises"].get("keys") or {}
        fails = [x for x in (r.get("line") or {}).get("failures", []) if x.startswith("trace_premises")]
        w(f"    {r['name']:26} {','.join(fails)}: {keys.get('violations')} unit records with keys >= N = "
          f"{n(r['trace_premises']['N'])} (max {n(keys.get('max_key') or 0)}), all forced: "
          f"{keys.get('all_forced')}")
    w("  why: a forced top overflow (and a forced tier fill) needs more keys homed to one top bucket "
      "than the about 32 keys below N = 32 T that home there; the dumper's key search then passes N")
    w("")

    # ---- P3 ------------------------------------------------------------------
    w("P3 (TracePremises.load: at most a U_1 = 32 U_1 records per level-one ordinal)")
    w("  'reaches its bound' = some captured level-one ordinal holds exactly 32 U_1 records "
      "(trace_premises.load.max_records = load.bound)")
    nonsel = [r for r in runs if not r["facts"]["selected"]]
    at = [r for r in nonsel if r["facts"]["load_max"] == r["facts"]["load_bound"]]
    over = [r for r in runs if r["facts"]["load_max"] > r["facts"]["load_bound"]]
    w(f"  never over the bound: {len(runs) - len(over)} of {len(runs)} runs")
    w(f"  non-selected runs reaching their bound: {len(at)} of {len(nonsel)}: "
      + ", ".join(f"{r['name']} ({r['facts']['load_max']})" for r in at))
    nonsel_orig = [r for r in orig if not r["facts"]["selected"]]
    at_orig = [r for r in nonsel_orig if r["facts"]["load_max"] == r["facts"]["load_bound"]]
    w(f"    of the base battery: {len(at_orig)} of {len(nonsel_orig)}")
    hist = {}
    for r in nonsel:
        f = r["facts"]
        hist.setdefault((f["load_bound"]), []).append(f["load_max"])
    for b in sorted(hist):
        w(f"    bound {b:4}: maxima {sorted(hist[b])}")
    for r in runs:
        f = r["facts"]
        if f["selected"]:
            w(f"  {r['name']:26} max {f['load_max']} of {f['load_bound']} records per ordinal "
              f"({f['load_ordinals']} ordinals)")
    w("")

    # ---- P6 ------------------------------------------------------------------
    w("P6 (UnshPromise: every run that evaluates the top, i.e. every non-selected run)")
    w("  finishes = top finishes evaluated; flagged = flagged carry tombstones checked (main and tier, "
      "sufficient form); in tier = of them in a carry's tier (the exact form's instance); "
      "shadowing = unflagged carry tombstones that shadow a live older copy (where a wrongly set "
      "flag would be caught); tier shadowing = unflagged tier tombstones with a live copy in C")

    def p6(rs):
        s = {"finishes": 0, "unsh_checked": 0, "flagged_in_b_tier": 0, "unflagged_shadowing": 0,
             "unflagged_shadowing_in_b_tier": 0}
        for r in rs:
            up = r.get("unsh_promise") or {}
            if up.get("result") in (None, "n/a"):
                continue
            for k in s:
                s[k] += up.get(k) or 0
        return s

    for label, rs in (("all runs", runs), (f"the base battery ({len(orig)} runs)", orig)):
        s = p6(rs)
        w(f"  {label}: {n(s['finishes'])} finishes / {n(s['unsh_checked'])} flagged / "
          f"{n(s['flagged_in_b_tier'])} in tier / {n(s['unflagged_shadowing'])} shadowing "
          f"(tier shadowing {n(s['unflagged_shadowing_in_b_tier'])}); violations: "
          f"{sum(1 for r in rs if (r.get('unsh_promise') or {}).get('result') == 'fail')} runs")
    for k in KIND_ORDER:
        if k in kinds and not k.startswith("selected"):
            s = p6(kinds[k])
            w(f"    {k:20} {s['finishes']} / {s['unsh_checked']} / {s['flagged_in_b_tier']} / "
              f"{s['unflagged_shadowing']}")
    w("")

    # ---- fail closed -------------------------------------------------------
    w("FAIL CLOSED")
    w("  every run: the oracle's evidence checks pass (ops, units, levels, contents, coverage, dumper "
      "checks), compared = tables - skipped, checks.failures empty, shapes.init = shapes.prep, both "
      "engines' views record every completed operation and their dummy counters form one chain")
    w(f"  runs failing a driver check: {sum(1 for r in runs if r.get('notes'))}")
    mu = rep["mutations"]["cases"]
    vac = [m for m in mu if m["name"].startswith("vac_")]
    w(f"  mutations: {sum(1 for m in mu if m['ok'])} of {len(mu)} rejected as expected "
      f"({len(vac)} of them vacuity probes, {sum(1 for m in vac if m['ok'])} caught)")
    for m in vac:
        how = f"exit {m['exit']}" + (f" {m['error'][:70]!r}" if m["exit"] == 2 else
                                     f" {','.join(m['reasons'])[:90]}")
        w(f"    {m['name']:28} {'caught' if m['ok'] else 'NOT CAUGHT'} ({how})")
    sh = rep.get("shapes") or {}
    for line in sh.get("lines", []):
        w(f"  shapes: {line.split('/')[-1]}")
    for k, v in (sh.get("mutations_caught") or {}).items():
        w(f"  shapes mutation {k}: {'caught' if v else 'NOT CAUGHT'}")
    w("")

    # ---- two secrets ---------------------------------------------------------
    ts = rep.get("two_secret") or {}
    w("WORD INDEPENDENCE OF THE SCHEDULE (two engine secrets, same operations)")
    for p in ts.get("pairs", []):
        w(f"  {p['pair']:24} {'identical' if p['ok'] else 'DIFFERS ' + str(p.get('diffs'))}: drive "
          f"{p.get('drive')}, policy {p.get('policy')}, batch {p.get('batch')}; plans, counters and real "
          f"flags of {n(p.get('entries', 0))} plan entries (both engines; {n(p.get('touched_differ', 0))} "
          f"touched buckets differ), units, outcome, {p.get('tables')} tables' descriptors and record "
          f"sets ({p.get('tables_placed_differently')} placed differently)")
    w("")

    with open(sys.argv[2], "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"summary: {sys.argv[2]}")
    return 0 if rep["all_ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
