#!/usr/bin/env python3
"""Deterministically generate selected direct A range certificates.

Reuses integrated NCA1/NCA5 integer computations and their soundness theorems.
Only this package's files are written. Run from any directory with Python 3.

A radix class law's thinned table and partial sums depend only on its chain key
(SelRange3's `chain_key`: depth, mass in lowest terms, radix, cutoff). A class
whose key is one of SelRange3's chains uses SelRange3's tables and checks
(`D6B`: SelRange3's `T4K6B`); a class whose key an earlier class of this package
has uses that class's (`D6A`: `D3A`). Every class keeps its own final check.
"""
import importlib.util
import math
import multiprocessing as mp
from pathlib import Path
import sys
sys.set_int_max_str_digits(0)
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
PKG = 'RebuildBound.Proofs.DirectJobANumerics'

def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod
bgen = load('direct_binary_gen', HERE.parent / 'SelRange1/gen.py')
rgen = load('direct_radix_gen', HERE.parent / 'SelRange3/gen.py')
HEADER = '/-! Generated by `DirectJobANumerics/gen.py`; exact integer certificates. -/\n'

def write(name, body):
    (HERE / (name + '.lean')).write_text(body)

def table(name, rows):
    body = HEADER + '\nnamespace RebuildBound.DirectJobANumerics.Tab\n\n'
    for i, row in enumerate(rows):
        body += f'def {name}_r{i} : List Nat := [{", ".join(map(str,row))}]\n\n'
    body += f'def {name} : List (List Nat) := [{", ".join(f"{name}_r{i}" for i in range(len(rows)))}]\n\n'
    body += 'end RebuildBound.DirectJobANumerics.Tab\n'
    write('Tab' + name, body)

SR3 = 'RebuildBound.Proofs.SelRange3'

# pool workers (module-level, so that they pickle)
def chain_job(key):
    return rgen.run_chain(key)

def final_job(job):
    return rgen.run_final(job)

def chain_names(ch):
    """Lean names of a chain's tables and checks, here or in SelRange3."""
    cid = ch['cid']
    if ch['ext']:
        return dict(th=f'SelRange3.Tab.{cid}_th', s=lambda n: f'SelRange3.Tab.{cid}_s{n}',
                     smod=lambda n: f'{SR3}.Tab{cid}s{n}', thin=f'SelRange3.thin_{cid}',
                     conv=lambda n: f'SelRange3.conv_{cid}_{n}', lane=f'{SR3}.Lane{ch["lane"]}')
    return dict(th=f'Tab.{cid}th', s=lambda n: f'Tab.{cid}s{n}',
                smod=lambda n: f'{PKG}.Tab{cid}s{n}', thin=f'thin{cid}',
                conv=lambda n: f'conv{cid}_{n}', lane=f'{PKG}.Lane{ch["lane"]}')

def main():
    imports = ['RebuildBound.Spec.DirectJobANumerics', 'RebuildBound.Proofs.SelRange1.T6P128I1', 'RebuildBound.Proofs.SelRange3.Glue']
    range_proofs = {}
    for digit, t in ((2,5),(4,6)):
        P,I = 64,0
        fp = bgen.final(bgen.read_table(t),t,P,I)
        name = f'Binary{digit}'
        src = 'import RebuildBound.Proofs.SelRange1.Glue\n' + HEADER
        src += '\nopen RebuildBound.Spec RebuildBound.Model\nopen scoped ENNReal\nnamespace RebuildBound.DirectJobANumerics\n\n'
        src += f'theorem final{digit} : NCA1.checkFinal {fp["wf"]} (2 ^ 320) 100 {fp["rr"]} 32 256 64 (2 ^ 0) 64 1 (2 ^ {t}) 32 1 {t} {fp["fuel"]} {fp["tn"]} (10 ^ {fp["tde"]}) {fp["s"]} NCA1.Tab.t{t} = true := by\n  decide +kernel\n\n'
        src += f'theorem range{digit} : stopLoss (rangeLaw 64 32 64 (halfPow {t}) (2 ^ 0) {t}) 64 ≤ ({fp["tn"]} : ℝ≥0∞) / (10 ^ {fp["tde"]} : ℕ) :=\n  SelRange1.range_le final{digit} SelRange1.bnd{t} (by norm_num)\n\nend RebuildBound.DirectJobANumerics\n'
        write(name,src)
        imports.append(PKG + '.' + name)
        range_proofs[digit]=(fp['tn'],fp['tde'],f'range{digit}')
        print('binary',digit,float(fp['total']),flush=True)
    range_proofs[8]=(41706,39,'SelRange1.range_T6P128I1')

    shapes=((3,3,4,4,64,0),(5,5,3,4,128,1),(6,3,4,5,128,1),(7,7,3,4,128,1))
    # the chains: SelRange3's, then this package's in class order
    chains={key:dict(ch,ext=True) for key,ch in rgen.plan(rgen.parse_budgets())[2].items()}
    classes={}
    for slot,(digit,r,t,k,P,I) in enumerate(shapes):
        nb=64-k
        cls=[]
        for ci,(X,qc) in enumerate((('A',2**nb//r+1),('B',2**nb//r))):
            cid=f'D{digit}{X}';lane=(2*slot+ci)%4
            key=rgen.chain_key(t,qc,nb,r)
            ch=chains.setdefault(key,dict(cid=cid,lane=lane,users=[],ext=False))
            ch['users'].append(cid)
            cls.append(dict(X=X,qc=qc,cid=cid,lane=lane,key=key))
        classes[digit]=(r,t,k,P,I,cls)
    used={c['key'] for _,_,_,_,_,cls in classes.values() for c in cls}
    pool=mp.Pool(8)
    for ch in pool.map(chain_job,sorted(used)):
        chains[ch['key']].update(ch)
    lanes=[([],[]) for _ in range(4)]
    for digit,(r,t,k,P,I,cls) in classes.items():
        nb=64-k
        fps=pool.map(final_job,[(chains[c['key']]['steps'][-1][1],P,I,c['qc'],2**(nb+t)) for c in cls])
        total=max(fp['total'] for fp,_ in fps)
        ex=math.floor(math.log10(total.numerator)-math.log10(total.denominator))-4
        td=10**(-ex);tn=math.ceil(total*td)
        print('radix',digit,'target',tn,'/',td,flush=True)
        for c,(fp,_) in zip(cls,fps):
            assert (fp['fin'] + bgen.D * fp['tail']) * td <= tn * bgen.D * bgen.D
            c.update(fp=fp,tn=tn,tde=-ex)
        for c in cls:
            qc=c['qc'];fp=c['fp'];cid=c['cid'];ch=chains[c['key']];nm=chain_names(ch)
            print(f'  {cid}: chain {ch["cid"]} ({ch["qcT"]}/2^{ch["nbT"]}, thin w {ch["wT"]})',flush=True)
            imps, checks=lanes[c['lane']]
            # Assign classes independently; checks within a lane remain sequential.
            if not ch['ext'] and ch['cid']==cid:
                table(cid+'th',ch['Tb'])
                imps.extend([f'RebuildBound.Proofs.NCA1.Tab{t}',PKG+'.Tab'+cid+'th'])
                checks.append(f'theorem thin{cid} : NCA5.checkThin {ch["wT"]} {ch["qcT"]} (2 ^ {ch["nbT"]}) 64 256 NCA1.Tab.t{t} Tab.{cid}th = true := by\n  decide +kernel\n')
                prev=f'Tab.{cid}th'
                for n,(w,S) in enumerate(ch['steps'],2):
                    table(cid+f's{n}',S)
                    imps.append(PKG+'.Tab'+cid+f's{n}')
                    checks.append(f'theorem conv{cid}_{n} : NCA5.checkConv {w} (2 ^ 320) 256 {prev} Tab.{cid}th Tab.{cid}s{n} = true := by\n  decide +kernel\n')
                    prev=f'Tab.{cid}s{n}'
            imps.append(nm['smod'](r))
            checks.append(f'theorem final{cid} : NCA1.checkFinal {fp["wf"]} (2 ^ 320) 100 {fp["rr"]} 32 256 64 (2 ^ {I}) {P} {qc} (2 ^ {nb+t}) 32 1 0 {fp["fuel"]} {tn} (10 ^ {-ex}) 0 [NCA5.rootMarg 64 {nm["s"](r)}] = true := by\n  decide +kernel\n')
    pool.close()
    pool.join()
    for j,(imps,checks) in enumerate(lanes):
        src=''.join(f'import {imp}\n' for imp in dict.fromkeys(['RebuildBound.Proofs.NCA5.Checker']+imps))+HEADER
        src+='\nset_option Elab.async false\nnamespace RebuildBound.DirectJobANumerics\n\n'+'\n'.join(checks)+'\nend RebuildBound.DirectJobANumerics\n'
        write(f'Lane{j}',src)
        imports.append(PKG+f'.Lane{j}')
    for _,_,_,_,_,cls in classes.values():
        for c in cls:
            ln=chain_names(chains[c['key']])['lane']
            if ln not in imports:
                imports.append(ln)

    src=''.join(f'import {imp}\n' for imp in imports)+HEADER
    src+='\nopen RebuildBound.Spec RebuildBound.Model\nopen scoped ENNReal\nnamespace RebuildBound.DirectJobANumerics\n\n'
    for digit,(r,t,k,P,I,cls) in classes.items():
        nb=64-k
        for c in cls:
            cid=c['cid'];qc=c['qc'];tn=c['tn'];te=c['tde'];ch=chains[c['key']];nm=chain_names(ch)
            steps=', '.join(f'({w}, {nm["s"](n)})' for n,(w,_) in enumerate(ch['steps'],2))
            convs=', '.join(nm['conv'](n) for n in range(2,r+1))
            hqT='rfl' if (ch['qcT'],ch['nbT'])==(qc,nb) else '(by norm_num)'
            src+=f'theorem class{cid} (q : unitInterval) (hq : (q : ℝ) = (({qc} : ℕ) : ℝ) / ((2 ^ {nb} : ℕ) : ℝ)) :\n  stopLoss (rangeLawR 64 32 {P} (2 ^ {I}) {t} {r} q) 64 ≤ ({tn} : ℝ≥0∞) / (10 ^ {te} : ℕ) + (2 ^ {I} : ℝ≥0∞) / 10 ^ 46 :=\n  SelRange3.class_bound RebuildBound.P10r (r := {r}) (t := {t}) (P := {P}) (i := {I}) (nb := {nb})\n    (qc := {qc}) (qcT := {ch["qcT"]}) (nbT := {ch["nbT"]}) (steps := [{steps}]) q hq SelRange1.bnd{t} rfl\n    (by norm_num) (by norm_num) (by norm_num) rfl {hqT} {nm["thin"]} ⟨{convs}, trivial⟩ final{cid}\n\n'
    for digit in range(2,9):
        e=bgen.val2(digit);r=digit//2**e;k=4+e;I=0 if digit<=4 else 1;t=k-I;P=64+64*I
        olde=bgen.val2(digit-1);oldr=(digit-1)//2**olde;m=64-(4+olde);num=oldr*((2**m+oldr-1)//oldr);n=32*(digit-1)*16
        src+=f'theorem selectedRange{digit} : selRange (selectedDirectSep {digit}) ≤ ENNReal.ofReal (1 / (2 : ℝ) ^ 103) := by\n'
        if r==1:
            tn,te,thm=range_proofs[digit]
            src+=f'  have h := SelRange1.selRange_le (selectedDirectSep {digit}) (q := (1 : ℚ) / 2 ^ 103)\n    (t := {t}) (i := {I}) (P := {P}) (n := {n}) (m := {m}) (num := {num})\n    (tn := {tn}) (td := 10 ^ {te}) (bn := 1) (bd := 2 ^ 103)\n    rfl rfl rfl rfl rfl rfl rfl rfl {thm} (by norm_num)\n    (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)\n\n'
        else:
            _,_,_,_,_,cls=classes[digit];tn=cls[0]['tn'];te=cls[0]['tde'];nb=64-k;qa=2**nb//r+1;qb=2**nb//r
            src+=f'  have h := SelRange3.selRange_le (selectedDirectSep {digit}) (q := (1 : ℚ) / 2 ^ 103)\n    (r := {r}) (t := {t}) (i := {I}) (P := {P}) (nb := {nb}) (qcA := {qa}) (qcB := {qb})\n    (n := {n}) (m := {m}) (num := {num}) (tn := {tn}) (td := 10 ^ {te}) (bn := 1) (bd := 2 ^ 103)\n    rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl rfl\n    classD{digit}A classD{digit}B (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)\n\n'
        src+='  norm_num at h ⊢\n  exact h\n\n'
    src+='end RebuildBound.DirectJobANumerics\n'
    write('Ranges',src)


if __name__ == '__main__':
    main()
