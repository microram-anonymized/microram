#!/usr/bin/env python3
"""Generate the SelRange5 certificate tables, kernel checks and per-shape theorems.

SelRange5 (`Spec/Selected.lean`): every `r = 5` shape of `selBudgets` meets its
range budget. Each shape has `d = 5`, so the old-map density is exactly 1 and
`selRange g = 2^t Σ_{a<5} stopLoss(rangeLawR 64 32 P 2^I t 5 q_a) 64` with
`t = k - I`, `P = earlyCap`, `q_a = qMass 64 k 5 a` (`Class.lean`).

* The shape with carry bits 13 is NCA5's instance: `RebuildBound.NCA5` is used
  as is (`Shape13.lean`); nothing is generated for it.
* For the other shapes (carry bits 7, 10, 16; `t = 4, 4, 6`) the class masses
  take two values `q = qc / 2^(64-k)` (`qc = 2^(64-k)/5 + [a < 2^(64-k) mod 5]`,
  classes `A` and `B`). Per class, NCA5's route at the shape's `t`, `P`, `I`:
  `Thin<S>` thins NCA1's depth-`t` table `Tab<t>` (not regenerated) by `q`
  (`checkThin`), `Conv<S><n>` bounds the partial sums `n = 2..5` of the radix
  node (`checkConv`), and `Final<S>` runs NCA1's `checkFinal` on the root-loss
  marginal with `p = qc / 2^(64-k+t)`, `g = 2^I`, `P`. The arithmetic is
  NCA5's generator's (`NCA5/gen.py`, imported), so every check holds by
  construction. `Shape<K>.lean` assembles the shape; one target `tn / td`
  (five significant digits, the larger class rounded up) serves both classes.

The shapes and budgets are parsed from `Spec/Selected.lean` (through
`SelRange1/gen.py`). No floating point enters a table or a check.
Usage: `python3 gen.py` (about 3 minutes; one process per class law).
"""
import importlib.util
import math
import multiprocessing as mp
import sys
import time
from fractions import Fraction as Q
from pathlib import Path

sys.set_int_max_str_digits(0)
sys.dont_write_bytecode = True  # keep the other packages' directories clean
HERE = Path(__file__).resolve().parent


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


S1 = load('selrange1gen', HERE.parent / 'SelRange1' / 'gen.py')   # budgets, shapes, tables
N5 = load('nca5gen', HERE.parent / 'NCA5' / 'gen.py')              # thin, conv, rootMarg
G1 = N5.G1                                                         # NCA1's generator

C, H, L = N5.C, N5.H, N5.L        # 64, 256, 64
PREC, D = N5.PREC, N5.D           # 2^320
R = 5
W = 64
LAM_A, LAM_B = N5.LAM_A, N5.LAM_B
SIGDIG = 5
EPS_EXP = 47                      # P10r's term per root: ≤ 10^-47 (`Class.lean`, `eps_bound6`)
NCA5_K = 13
cdiv = N5.cdiv


def choose_list(P, n):
    out, c = [], 1
    for j in range(n):
        out.append(c)
        c = c * max(P - j, 0) // (j + 1)
    return out


def final(Rm, ap, dp, P, G):
    """NCA1's `checkFinal` on the one-row table `[Rm]` with `t = 0`, `s = 0`:
    returns `fin` (scale D^2), `tail` (scale D) and the check's parameters."""
    cs = Rm + [0] * (H + 1 - len(Rm))
    assert len(cs) == H + 1
    Qv = [D] + cs[1:]
    W2 = sum(cs[j] << j for j in range(1, H + 1))
    wf = 2 * PREC + 8
    Wd = G1.Width(wf)
    fuel = G.bit_length()
    G1.H = H
    A = G1.pow_round(Wd, Qv, fuel, G)
    # ℕ subtraction, as in `binomRow`
    bl = [cdiv(D * c * ap ** j * (dp - ap) ** max(P - j, 0), dp ** P)
          for j, c in enumerate(choose_list(P, H + 1))]
    assert sum(bl) * sum(A) < 1 << wf
    cc = G1.conv_trunc(bl, A, H + 1)
    fin = sum(cc[n] * max(n - L, 0) for n in range(H + 1))
    rr = max(1, cdiv(G * W2, D))
    assert G * W2 <= D * rr
    um = G1.umNum(G1.NTAYLOR, rr, G * W2, D)
    tail = cdiv((H + 1 - L) * (dp + ap) ** P * um, 2 ** (H + 1) * dp ** P)
    return dict(fin=fin, tail=tail, wf=wf, fuel=fuel, rr=rr,
                total=Q(fin, D * D) + Q(tail, D))


# --- emitting Lean -------------------------------------------------------------------
def write(path, text):
    """Write only when the content changes (lake may be building the old file)."""
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


HEADER = '/-! {doc} Generated by `RebuildBound/Proofs/SelRange5/gen.py`; do not edit. -/\n\n'
MOD = 'RebuildBound.Proofs.SelRange5'


def emit_table(fname, name, F, doc):
    out = [HEADER.format(doc=doc), 'namespace RebuildBound.SelRange5.Tab\n']
    for m, row in enumerate(F):
        out.append(f'def {name}_r{m} : List Nat := [{", ".join(map(str, row))}]\n')
    out.append(f'def {name} : List (List Nat) :=\n  [{", ".join(f"{name}_r{m}" for m in range(len(F)))}]\n')
    out.append('end RebuildBound.SelRange5.Tab')
    write(HERE / f'{fname}.lean', '\n'.join(out) + '\n')


def emit_check(fname, imports, doc, thm, stmt):
    write(HERE / f'{fname}.lean',
        ''.join(f'import {i}\n' for i in imports) + '\n' +
        HEADER.format(doc=doc) +
        'namespace RebuildBound.SelRange5\n\n'
        f'/-- {doc} -/\n'
        f'theorem {thm} : {stmt} = true := by\n'
        '  decide +kernel\n\nend RebuildBound.SelRange5\n')


def shape_params(s):
    sp = S1.shape_params(s)
    g = s['g']
    assert g['r'] == R and g['C'] == C and g['e'] == 0
    qe = W - sp['k']
    QD = 2 ** qe
    sp.update(qe=qe, QD=QD, nA=QD % R,
              cls={'A': QD // R + 1, 'B': QD // R})
    # d - 1 = 4: the old-map density is exactly 1
    assert sp['num'] == 2 ** sp['m']
    return sp


def run_class(job):
    """One class law: thin, four partial sums, the final series."""
    K, X, t, P, I, qe, qc = job
    st = time.time()
    tag = f'K{K}{X}'
    F = S1.read_table(t)
    F = [N5.trim(r) for r in F]
    log = []
    Tb, w = N5.thin(F, qc, 2 ** qe)
    emit_table(f'TabThin{tag}', f'th{tag}', Tb,
               f'Upper table of `(truncTree 64 32 256 {t}).bind (thinPair q)`, `q = {qc}/2^{qe}`, '
               f'at scale `2^{PREC}`.')
    emit_check(f'Thin{tag}', [f'RebuildBound.Proofs.NCA5.Checker', f'RebuildBound.Proofs.NCA1.Tab{t}',
                              f'{MOD}.TabThin{tag}'],
               f'Kernel check of the thinning of `Tab.t{t}` by `{qc}/2^{qe}` (carry bits {K}, class {X}).',
               f'thin{tag}',
               f'NCA5.checkThin {w} {qc} (2 ^ {qe}) {C} {H} NCA1.Tab.t{t} Tab.th{tag}')
    log.append(f'{tag}: thin w {w}, mass {float(Q(sum(map(sum, Tb)), D)):.15f}, {time.time() - st:.0f}s')
    S, prev, prev_mod = Tb, f'Tab.th{tag}', f'{MOD}.TabThin{tag}'
    for n in range(2, R + 1):
        S, w = N5.conv(S, Tb)
        emit_table(f'TabS{tag}{n}', f's{tag}{n}', S,
                   f'Upper table of partial sum {n} of the radix node (carry bits {K}, class {X}), '
                   f'at scale `2^{PREC}`.')
        imps = ['RebuildBound.Proofs.NCA5.Checker', f'{MOD}.TabThin{tag}', f'{MOD}.TabS{tag}{n}']
        if n > 2:
            imps.insert(2, prev_mod)
        emit_check(f'Conv{tag}{n}', imps,
                   f'Kernel check of partial sum {n} of the radix node (carry bits {K}, class {X}).',
                   f'conv{tag}{n}',
                   f'NCA5.checkConv {w} (2 ^ {PREC}) {H} {prev} Tab.th{tag} Tab.s{tag}{n}')
        log.append(f'{tag}: conv {n} w {w}, rows {len(S)}, '
                   f'mass {float(Q(sum(map(sum, S)), D)):.15f}, {time.time() - st:.0f}s')
        prev, prev_mod = f'Tab.s{tag}{n}', f'{MOD}.TabS{tag}{n}'
    p = final(N5.root_marg(S), qc, 2 ** (qe + t), P, 2 ** I)
    p['prev'], p['prev_mod'] = prev, prev_mod
    log.append(f'{tag}: final fin {float(Q(p["fin"], D * D)):.12e}, tail {float(Q(p["tail"], D)):.3e}, '
               f'total {float(p["total"]):.12e}, {time.time() - st:.0f}s')
    return job, p, log


def target(total):
    ex = math.floor(math.log10(total.numerator) - math.log10(total.denominator)) - (SIGDIG - 1)
    assert ex < 0
    return math.ceil(total * 10 ** (-ex)), -ex


def emit_final(job, p, tn, tde):
    K, X, t, P, I, qe, qc = job
    tag = f'K{K}{X}'
    td = 10 ** tde
    assert (p['fin'] + D * p['tail']) * td <= tn * D * D
    emit_check(f'Final{tag}', ['RebuildBound.Proofs.NCA5.Checker', p['prev_mod']],
               f'Kernel check of the stop-loss series from the root-loss marginal (carry bits {K}, class {X}).',
               f'final{tag}',
               f'NCA1.checkFinal {p["wf"]} (2 ^ {PREC}) {G1.NTAYLOR} {p["rr"]} {G1.RRED} {H} {L} '
               f'(2 ^ {I}) {P} {qc} (2 ^ {qe + t}) {LAM_A} {LAM_B} 0 {p["fuel"]} '
               f'{tn} (10 ^ {tde}) 0 [NCA5.rootMarg {C} {p["prev"]}]')


def class_args(tag, t):
    return (f'SelRange1.bnd{t} thin{tag} conv{tag}2 conv{tag}3 conv{tag}4 conv{tag}5 final{tag}')


def emit_shape(s, sp, tn, tde, value):
    K, t, I, P, qe = s['g']['K'], sp['t'], sp['I'], sp['P'], sp['qe']
    imports = [f'{MOD}.Class']
    for X in 'AB':
        imports += [f'{MOD}.ThinK{K}{X}'] + [f'{MOD}.ConvK{K}{X}{n}' for n in range(2, R + 1)] + \
                   [f'{MOD}.FinalK{K}{X}']
    qA, qB = sp['cls']['A'], sp['cls']['B']
    lines = [''.join(f'import {i}\n' for i in imports),
             HEADER.format(doc=f'The `r = 5` shape with carry bits {K}: `t = {t}`, `P = {P}`, `g = 2^{I}`, '
                               f'class masses `{qA}/2^{qe}` (A) and `{qB}/2^{qe}` (B).'),
             'open RebuildBound.Spec RebuildBound.Model',
             'open scoped ENNReal\n',
             'namespace RebuildBound.SelRange5\n',
             f'/-- The class sum at carry bits {K}: every class is at most `{tn}/10^{tde} + 2^{I}/10^47`. -/',
             f'theorem sum_K{K} : ∑ a ∈ Finset.range 5, stopLoss (rangeLawR 64 32 {P} (2 ^ {I}) {t} 5 '
             f'(qMass 64 {sp["k"]} 5 a)) 64 ≤',
             f'    5 * ((({tn} : ℕ) : ℝ≥0∞) / ((10 ^ {tde} : ℕ) : ℝ≥0∞) + ((2 ^ {I} : ℕ) : ℝ≥0∞) / 10 ^ 47) :=',
             f'  shape_sum (k := {sp["k"]}) (qe := {qe})',
             f'    (f := fun q => stopLoss (rangeLawR 64 32 {P} (2 ^ {I}) {t} 5 q) 64) rfl',
             f'    (fun q hq => class_bound (qc := {qA}) (qe := {qe}) q (hq.trans (by norm_num)) (by norm_num)',
             f'      (by norm_num) (by norm_num) (by norm_num) {class_args(f"K{K}A", t)})',
             f'    (fun q hq => class_bound (qc := {qB}) (qe := {qe}) q (hq.trans (by norm_num)) (by norm_num)',
             f'      (by norm_num) (by norm_num) (by norm_num) {class_args(f"K{K}B", t)})\n',
             f'/-- {s["name"]}: range term `≤ {float(value):.6e}`, budget `{s["bn"]} / 10^{s["be"]}`. -/',
             f'theorem {S1.shape_ident(s)} : selRange {s["geom"]} ≤',
             f'    ENNReal.ofReal (({s["bn"]} / 10 ^ {s["be"]} : ℚ) : ℝ) :=',
             f'  selRange_le5 {s["geom"]}',
             f'    (t := {t}) (i := {I}) (P := {P}) (k := {sp["k"]}) rfl rfl rfl rfl rfl rfl rfl sum_K{K}',
             f'    (budget_le (bn := {s["bn"]}) (bd := 10 ^ {s["be"]}) (by norm_num) (by norm_num) (by norm_num)',
             f'      (by norm_num))\n',
             'end RebuildBound.SelRange5']
    write(HERE / f'Shape{K}.lean', '\n'.join(lines) + '\n')


def emit_nca5(s, sp):
    K, t, I, P = s['g']['K'], sp['t'], sp['I'], sp['P']
    value = 2 ** t * Q(7107, 10 ** 30)
    lines = [f'import {MOD}.Class\nimport RebuildBound.Proofs.NCA5fin\n',
             HEADER.format(doc=f'The `r = 5` shape with carry bits {K}, NCA5\'s instance: `t = {t}`, '
                               f'`P = {P}`, `g = 2^{I}`; the class sum is `RebuildBound.NCA5`.'),
             'open RebuildBound.Spec RebuildBound.Model',
             'open scoped ENNReal\n',
             'namespace RebuildBound.SelRange5\n',
             f'/-- {s["name"]}: range term `≤ {float(value):.6e}` (NCA5), budget `{s["bn"]} / 10^{s["be"]}`. -/',
             f'theorem {S1.shape_ident(s)} : selRange {s["geom"]} ≤',
             f'    ENNReal.ofReal (({s["bn"]} / 10 ^ {s["be"]} : ℚ) : ℝ) :=',
             f'  selRange_le5 {s["geom"]}',
             f'    (t := {t}) (i := {I}) (P := {P}) (k := {sp["k"]}) (X := ((7107 : ℕ) : ℝ≥0∞) / 10 ^ 30)',
             '    rfl rfl rfl rfl rfl rfl rfl (RebuildBound.NCA5.trans_eq (by rw [Nat.cast_ofNat]))',
             f'    (budget_le\' (bn := {s["bn"]}) (bd := 10 ^ {s["be"]}) (by norm_num) (by norm_num) (by norm_num))\n',
             'end RebuildBound.SelRange5']
    write(HERE / f'Shape{K}.lean', '\n'.join(lines) + '\n')


