def emit_main(budgets, r5):
    imports = ''.join(f'import {MOD}.Shape{s["g"]["K"]}\n' for s in r5)
    cases = []
    for s in budgets:
        if s['g']['r'] == R:
            cases.append(f'  · intro _; exact SelRange5.{S1.shape_ident(s)}')
        else:
            cases.append('  · intro hr; exact absurd hr (by decide)')
    pattern = ' | '.join(['rfl'] * len(budgets))
    src = imports + MAIN.replace('@DOC@', DOC).replace('@PATTERN@', pattern).replace('@CASES@', '\n'.join(cases))
    write(HERE.parent / 'SelRange5.lean', src)


def main():
    budgets = S1.parse_budgets()
    r5 = [s for s in budgets if s['g']['r'] == R]
    assert len(r5) == 4
    jobs = []
    for s in r5:
        sp = shape_params(s)
        s['sp'] = sp
        assert 4 <= sp['t'] <= 6 and sp['I'] <= 10
        if s['g']['K'] == NCA5_K:
            assert (sp['t'], sp['P'], sp['I'], sp['k']) == (5, 1088, 8, 13)
            # NCA5: Σ ≤ 7107 / 10^30, so selRange ≤ 2^5 · 7107 / 10^30
            assert 2 ** 5 * 7107 * 10 ** s['be'] <= s['bn'] * 10 ** 30
            emit_nca5(s, sp)
            print(f'{s["name"]}: NCA5, value {2 ** 5 * 7107e-30:.6e}, budget {s["bn"]}e-{s["be"]}, '
                  f'margin {1 - 2 ** 5 * 7107e-30 / (s["bn"] * 10.0 ** -s["be"]):.4%}')
            continue
        for X in 'AB':
            jobs.append((s['g']['K'], X, sp['t'], sp['P'], sp['I'], sp['qe'], sp['cls'][X]))
    with mp.Pool(len(jobs)) as pool:
        res = pool.map(run_class, jobs)
    out = {}
    for job, p, log in res:
        print('\n'.join(log))
        out[(job[0], job[1])] = (job, p)
    for s in r5:
        K = s['g']['K']
        if K == NCA5_K:
            continue
        sp = s['sp']
        t, I = sp['t'], sp['I']
        tot = max(out[(K, 'A')][1]['total'], out[(K, 'B')][1]['total'])
        tn, tde = target(tot)
        td = 10 ** tde
        for X in 'AB':
            emit_final(*out[(K, X)], tn, tde)
        bd = 10 ** s['be']
        # the arithmetic of `budget_le`
        lhs = 2 ** t * R * (tn * 10 ** EPS_EXP + 2 ** I * td) * bd
        rhs = s['bn'] * (td * 10 ** EPS_EXP)
        assert lhs <= rhs, (s['name'], lhs / rhs)
        value = 2 ** t * R * (Q(tn, td) + Q(2 ** I, 10 ** EPS_EXP))
        exact = 2 ** t * (sp['nA'] * out[(K, 'A')][1]['total'] + (R - sp['nA']) * out[(K, 'B')][1]['total'])
        print(f'{s["name"]}: classes A {float(out[(K, "A")][1]["total"]):.10e} (x{sp["nA"]}), '
              f'B {float(out[(K, "B")][1]["total"]):.10e}; target {tn}e-{tde}; '
              f'certified {float(exact):.6e}, value {float(value):.6e}, budget {s["bn"]}e-{s["be"]}, '
              f'margin {float(1 - Q(lhs, rhs)):.4%}')
        emit_shape(s, sp, tn, tde, value)
    emit_main(budgets, r5)


if __name__ == '__main__':
    main()
