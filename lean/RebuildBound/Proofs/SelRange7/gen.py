def emit_main(shs, info):
    imports = ['RebuildBound.Proofs.SelRange7.Glue'] + \
              [f'RebuildBound.Proofs.SelRange7.{s["tag"]}' for s in shs]
    lines = [''.join(f'import {i}\n' for i in imports)]
    lines.append(MAIN_DOC.replace('@DOC@', DOC.strip('\n')))
    lines += ['open RebuildBound.Spec RebuildBound.Model',
              'open scoped ENNReal\n',
              'namespace RebuildBound.SelRange7\n']
    for s in shs:
        sp, M, tag = s['sp'], s['M'], s['tag']
        I = info[tag]
        lines += [f'/-- {s["name"]}: range term `≤ {float(I["value"]):.6e}`, budget '
                  f'`{s["bn"]} / 10^{s["be"]}` (margin {float(I["margin"]):.3%}). -/',
                  f'theorem {shape_ident(s)} : selRange {s["geom"]} ≤',
                  f'    ENNReal.ofReal (({s["bn"]} / 10 ^ {s["be"]} : ℚ) : ℝ) :=',
                  f'  selRange7_le {s["geom"]}',
                  f'    (t := {sp["t"]}) (i := {sp["I"]}) (P := {sp["P"]}) (n := {sp["n"]}) (m := {sp["m"]})',
                  f'    (num := {sp["num"]}) (M := {M}) (qA := {s["qc"]["A"]}) (qB := {s["qc"]["B"]})',
                  f'    (tA := {I["tn"]["A"]}) (tB := {I["tn"]["B"]}) (td := 10 ^ {I["tde"]})',
                  f'    (bn := {s["bn"]}) (bd := 10 ^ {s["be"]})',
                  '    rfl rfl rfl rfl rfl rfl rfl rfl rfl (by norm_num) (by norm_num) (by norm_num)',
                  f'    class_{tag}A class_{tag}B (by norm_num)',
                  '    (by norm_num) (by norm_num) (by norm_num) (by norm_num) (by norm_num)\n']
    lines.append('end RebuildBound.SelRange7\n')
    budgets = S1.parse_budgets()
    pattern = ' | '.join(['rfl'] * len(budgets))
    cases = []
    for s in budgets:
        if s['g']['r'] == R:
            cases.append(f'  · intro _; exact SelRange7.{shape_ident(s)}')
        else:
            cases.append('  · intro hr; exact absurd hr (by decide)')
    lines += ['open RebuildBound.Spec in',
              '/-- **SelRange7.** -/',
              'theorem RebuildBound.SelRange7 : RebuildBound.Spec.SelRange7_statement := by',
              '  unfold SelRange7_statement SelRangeAt',
              '  intro x hx',
              '  simp only [selBudgets, List.mem_cons, List.not_mem_nil, or_false] at hx',
              f'  rcases hx with {pattern}'] + cases
    (PROOFS / 'SelRange7.lean').write_text('\n'.join(lines) + '\n')


def main():
    shs = shapes()
    with mp.Pool(len(shs)) as pool:
        res = pool.map(run_shape, shs)
    res = {r['tag']: r for r in res}
    for r in res.values():
        print('\n'.join(r['log']))
    info = {}
    for s in shs:
        tag, sp = s['tag'], s['sp']
        fps = res[tag]['fps']
        tots = {X: fps[X]['total'] for X in 'AB'}
        mx = max(tots.values())
        tde = (SIGDIG - 1) - math.floor(math.log10(mx.numerator) - math.log10(mx.denominator))
        td = 10 ** tde
        tn = {X: target(tots[X], tde) for X in 'AB'}
        for X in 'AB':
            assert (fps[X]['fin'] + D * fps[X]['tail']) * td <= tn[X] * D * D
        emit_shape(s, res[tag], tn, tde)
        two_m = 2 ** sp['m']
        delta = sp['num'] - two_m
        assert delta >= 0 and sp['n'] * delta < two_m
        Dd = two_m - sp['n'] * delta
        E = 10 ** EPS_EXP
        bd = 10 ** s['be']
        lhs = two_m * 2 ** sp['t'] * ((tn['A'] + 6 * tn['B']) * E + 7 * td) * bd
        rhs = s['bn'] * (Dd * (td * E))
        value = Q(two_m, Dd) * 2 ** sp['t'] * (Q(tn['A'] + 6 * tn['B'], td) + Q(7, E))
        exact = 2 ** sp['t'] * (tots['A'] + 6 * tots['B'])
        margin = 1 - Q(lhs, rhs)
        print(f'{s["name"]}: t {sp["t"]} P {sp["P"]} I {sp["I"]} M {s["M"]}: classes '
              f'{float(tots["A"]):.10e} {float(tots["B"]):.10e}; 2^t Σ {float(exact):.6e}, '
              f'with D and targets {float(value):.6e}, budget {s["bn"]}e-{s["be"]}, '
              f'margin {float(margin):.4%}, D - 1 <= {float(Q(two_m, Dd) - 1):.2e}')
        assert lhs <= rhs, f'budget not met: {s["name"]}'
        info[tag] = dict(tn=tn, tde=tde, value=value, margin=margin)
    emit_main(shs, info)


if __name__ == '__main__':
    main()
