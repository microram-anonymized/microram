#!/usr/bin/env python3
"""Generate the SelRange7 certificate tables, kernel checks and per-shape theorems.

SelRange7 (`Spec/Selected.lean`): every `r = 7` shape of `selBudgets` meets its
range budget,

    selRange g = D 2^t Σ_{a<7} stopLoss(rangeLawR 64 32 P 2^I t 7 (qMass 64 k 7 a)) 64,

`t = k - I`, `P = earlyCap`, `D` the old-map density (`d - 1 = 6`). For each
shape `2^M mod 7 = 1` (`M = 64 - k`), so class `0` has mass `qc_A / 2^M` with
`qc_A = ⌊2^M/7⌋ + 1` and classes `1..6` have `qc_B = ⌊2^M/7⌋`: two class laws per
shape (`qCount_eq`). Both are certified as in NCA5 (`NCA5/gen.py`, whose `thin`,
`conv` and `root_marg` are imported), sharing one chain of partial sums:

* `Tab<S>Th.lean`     the entrywise maximum of NCA1's depth-`t` tree law
                      (`Tab<t>.lean`, not regenerated) thinned by `qc_A/2^M`
                      and by `qc_B/2^M`, each rounded up to `D = 2^320`
                      (`checkThin`, once per mass);
* `Tab<S>S<n>.lean`   the `n`-th partial sum of the radix node, `n = 2..7`,
                      restricted to totals `≤ 256` (`checkConv`);
* `<S>.lean`          the ten kernel checks of the shape (two `checkThin`, six
                      `checkConv`, NCA1's `checkFinal` on `[rootMarg 64 S7]` with
                      `p = qc 2^-t / 2^M` once per mass), elaborated one at a
                      time (`Elab.async false`: the module's peak memory is that
                      of the thinning, not the sum of its checks), and the class
                      bounds `≤ tn / td + 10^-50` (`class_bound7`);
* `SelRange7.lean`    the four shape theorems (`selRange7_le`) and the case
                      split over `selBudgets`.

Shapes and budgets are parsed from `Spec/Selected.lean` (SelRange1's parser).
No floating point enters a check. Usage: `python3 gen.py` (about 6 minutes, one
process per shape).
"""
import importlib.util
import math
import multiprocessing as mp
import sys
import time
from fractions import Fraction as Q
from pathlib import Path

sys.set_int_max_str_digits(0)
sys.dont_write_bytecode = True  # keep the other packages' directories clean
HERE = Path(__file__).resolve().parent
PROOFS = HERE.parent


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


N5 = load('nca5gen', PROOFS / 'NCA5' / 'gen.py')      # thin, conv, root_marg; N5.G1 = NCA1's gen
S1 = load('sel1gen', PROOFS / 'SelRange1' / 'gen.py')  # parse_budgets, shape_params, read_table
G1 = N5.G1

C, H, L = 64, 256, 64
R = 7
PREC = 320
D = 1 << PREC
assert N5.D == D and G1.D == D and S1.D == D
NTAYLOR, RRED = G1.NTAYLOR, G1.RRED
LAM_A, LAM_B = 32, 1
W = 64
SIGDIG = 6              # significant digits of the per-class targets
EPS_EXP = 50            # per-class truncation term `≤ 10^-50` (`Class.lean`)


def cdiv(x, y):
    return (x + (y - 1)) // y


# --- the shapes ----------------------------------------------------------------------
def shape_ident(s):
    lvl, dig, conf = s['name'].replace('(', '').replace(')', '').split()
    return f'{"u" if conf == "uniform" else "h"}{lvl}{dig}'


def shapes():
    out = []
    for s in S1.parse_budgets():
        if s['g']['r'] != R:
            continue
        sp = S1.shape_params(s)
        g = s['g']
        assert g['C'] == C and g['e'] == 0
        M = W - sp['k']
        assert 2 ** M % R == 1
        s['sp'] = sp
        s['M'] = M
        s['tag'] = shape_ident(s)[1:3]            # L2 .. L5
        s['qc'] = {'A': 2 ** M // R + 1, 'B': 2 ** M // R}
        out.append(s)
    assert len(out) == 4
    return out


# --- the final check (NCA1's `checkFinal`, `t = 0`, `s = 0`) --------------------------------
def final(Rm, ap, dp, P, I):
    G = 2 ** I
    cs = Rm + [0] * (H + 1 - len(Rm))
    Qv = [D] + cs[1:]
    W2 = sum(cs[j] << j for j in range(1, H + 1))
    wf = 2 * PREC + 8
    Wd = G1.Width(wf)
    fuel = G.bit_length()
    A = G1.pow_round(Wd, Qv, fuel, G)
    choose, c = [], 1
    for j in range(H + 1):
        choose.append(c)
        c = c * max(P - j, 0) // (j + 1)
    bl = [cdiv(D * c * ap ** j * (dp - ap) ** max(P - j, 0), dp ** P) for j, c in enumerate(choose)]
    assert sum(bl) * sum(A) < 1 << wf
    cc = G1.conv_trunc(bl, A, H + 1)
    fin = sum(cc[n] * max(n - L, 0) for n in range(H + 1))
    rr = max(1, cdiv(G * W2, D))
    assert G * W2 <= D * rr
    um = G1.umNum(NTAYLOR, rr, G * W2, D)
    tail = cdiv((H + 1 - L) * (dp + ap) ** P * um, 2 ** (H + 1) * dp ** P)
    return dict(wf=wf, fuel=fuel, rr=rr, fin=fin, tail=tail, total=Q(fin, D * D) + Q(tail, D))


# --- emitting Lean -----------------------------------------------------------------
HEADER = '/-! {doc} Generated by `RebuildBound/Proofs/SelRange7/gen.py`; do not edit. -/\n\n'


def emit_table(fname, name, F, doc):
    out = [HEADER.format(doc=doc), 'namespace RebuildBound.SelRange7.Tab\n']
    for m, row in enumerate(F):
        out.append(f'def {name}_r{m} : List Nat := [{", ".join(map(str, row))}]\n')
    out.append(f'def {name} : List (List Nat) :=\n  [{", ".join(f"{name}_r{m}" for m in range(len(F)))}]\n')
    out.append('end RebuildBound.SelRange7.Tab')
    (HERE / f'{fname}.lean').write_text('\n'.join(out) + '\n')


def maxtab(A, B):
    """Entrywise maximum of two tables (rows padded with zeros, then trimmed)."""
    out = []
    for i in range(max(len(A), len(B))):
        ra = A[i] if i < len(A) else []
        rb = B[i] if i < len(B) else []
        n = max(len(ra), len(rb))
        ra = ra + [0] * (n - len(ra))
        rb = rb + [0] * (n - len(rb))
        out.append(N5.trim([max(x, y) for x, y in zip(ra, rb)]))
    return out


def run_shape(s):
    """Both class laws of one shape. The two thinned tables (masses `qc_A`, `qc_B`) are
    bounded by one table, their entrywise maximum, so the six partial sums are shared;
    the final checks differ in the early probability `p = qc 2^-t / 2^M`."""
    sp, M, tag = s['sp'], s['M'], s['tag']
    t, P, I = sp['t'], sp['P'], sp['I']
    st = time.time()
    log = []
    F = S1.read_table(t)
    thins = {X: N5.thin(F, s['qc'][X], 2 ** M) for X in 'AB'}
    Tb = maxtab(thins['A'][0], thins['B'][0])
    wT = {X: thins[X][1] for X in 'AB'}
    emit_table(f'Tab{tag}Th', f'{tag}th', Tb,
               f'Upper table of `(truncTree 64 32 256 {t}).bind (thinPair q)` for both '
               f'`q = {s["qc"]["A"]}/2^{M}` and `q = {s["qc"]["B"]}/2^{M}`, at scale `2^{PREC}`.')
    log.append(f'{tag}: thin w {wT["A"]} {wT["B"]}, mass {float(Q(sum(map(sum, Tb)), D)):.15f}, '
               f'{time.time() - st:.0f}s')
    S = Tb
    ws = []
    for n in range(2, R + 1):
        S, w = N5.conv(S, Tb)
        ws.append(w)
        emit_table(f'Tab{tag}S{n}', f'{tag}s{n}', S,
                   f'Upper table of partial sum {n} of the radix node, shape {tag}, at scale '
                   f'`2^{PREC}`.')
        log.append(f'{tag}: conv {n} w {w}, rows {len(S)}, mass {float(Q(sum(map(sum, S)), D)):.15f}, '
                   f'{time.time() - st:.0f}s')
    Rm = N5.root_marg(S)
    fps = {}
    for X in 'AB':
        fps[X] = final(Rm, s['qc'][X], 2 ** (M + t), P, I)
        fp = fps[X]
        log.append(f'{tag}{X}: final fin {float(Q(fp["fin"], D * D)):.12e}, tail '
                   f'{float(Q(fp["tail"], D)):.3e}, total {float(fp["total"]):.12e}, '
                   f'{time.time() - st:.0f}s')
    return dict(tag=tag, wT=wT, ws=ws, fps=fps, log=log)


def target(total, ex):
    """`tn` with `total ≤ tn / 10^ex`."""
    return math.ceil(total * 10 ** ex)


def emit_shape(s, res, tn, tde):
    """One module per shape: the ten kernel checks, elaborated one after the other
    (`Elab.async false`, so the module's peak memory is that of its largest check, the
    thinning), then the two class laws."""
    sp, M, tag = s['sp'], s['M'], s['tag']
    t, P, I = sp['t'], sp['P'], sp['I']
    qc = s['qc']
    pre = 'RebuildBound.Proofs.SelRange7'
    which = {'A': 'class 0', 'B': 'classes 1 to 6'}
    imps = [f'{pre}.Class', f'RebuildBound.Proofs.NCA1.Tab{t}', f'{pre}.Tab{tag}Th'] + \
           [f'{pre}.Tab{tag}S{n}' for n in range(2, R + 1)]
    lines = [''.join(f'import {i}\n' for i in imps),
             HEADER.format(doc=f'Shape {tag} (`t = {t}`, `P = {P}`, `g = 2^{I}`): the kernel checks '
                               f'and the two class laws, `q = {qc["A"]}/2^{M}` (class 0) and '
                               f'`q = {qc["B"]}/2^{M}` (classes 1 to 6). The checks are elaborated '
                               f'one at a time, so that their kernel memory is not added up.'),
             'open RebuildBound.Spec',
             'open scoped ENNReal unitInterval\n',
             'set_option Elab.async false\n',
             'namespace RebuildBound.SelRange7\n']

    def check(name, doc, stmt):
        return [f'/-- {doc} -/', f'theorem {name} : {stmt} = true := by', '  decide +kernel\n']

    for X in 'AB':
        lines += check(f'thin_{tag}{X}',
                       f'Kernel check of the thinning of NCA1\'s depth-{t} table by `{qc[X]}/2^{M}` '
                       f'({which[X]}).',
                       f'NCA5.checkThin {res["wT"][X]} {qc[X]} (2 ^ {M}) {C} {H} NCA1.Tab.t{t} Tab.{tag}th')
    prev = f'Tab.{tag}th'
    for n, w in zip(range(2, R + 1), res['ws']):
        lines += check(f'conv_{tag}{n}', f'Kernel check of partial sum {n} of the radix node.',
                       f'NCA5.checkConv {w} (2 ^ {PREC}) {H} {prev} Tab.{tag}th Tab.{tag}s{n}')
        prev = f'Tab.{tag}s{n}'
    for X in 'AB':
        fp = res['fps'][X]
        lines += check(f'final_{tag}{X}',
                       f'Kernel check of the stop-loss series from the root-loss marginal ({which[X]}).',
                       f'NCA1.checkFinal {fp["wf"]} (2 ^ {PREC}) {NTAYLOR} {fp["rr"]} {RRED} {H} {L} '
                       f'(2 ^ {I}) {P} {qc[X]} (2 ^ {M + t}) {LAM_A} {LAM_B} 0 {fp["fuel"]} {tn[X]} '
                       f'(10 ^ {tde}) 0 [NCA5.rootMarg {C} {prev}]')
    for X in 'AB':
        fp = res['fps'][X]
        lines += [f'/-- The class law ({which[X]}): certified `{float(fp["total"]):.10e}`. -/',
                  f'theorem class_{tag}{X} (q : I) (hq : (q : ℝ) = (({qc[X]} : ℕ) : ℝ) / ((2 ^ {M} : ℕ) : ℝ)) :',
                  f'    stopLoss (rangeLawR 64 32 {P} (2 ^ {I}) {t} 7 q) 64 ≤',
                  f'      (({tn[X]} : ℕ) : ℝ≥0∞) / ((10 ^ {tde} : ℕ) : ℝ≥0∞) + 1 / 10 ^ {EPS_EXP} :=',
                  f'  class_bound7 q hq (by norm_num) (by norm_num) (by norm_num) (by norm_num)',
                  f'    SelRange1.bnd{t} thin_{tag}{X} ' + ' '.join(f'conv_{tag}{n}' for n in range(2, R + 1)),
                  f'    final_{tag}{X}\n']
    lines.append('end RebuildBound.SelRange7')
    (HERE / f'{tag}.lean').write_text('\n'.join(lines) + '\n')


