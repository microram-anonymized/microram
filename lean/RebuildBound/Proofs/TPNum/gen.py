#!/usr/bin/env python3
"""Generate the TPNum certificate: the selected top's range term.

The range law of the selected top (`Spec/TopPrepG.lean`) is
`rangeLawR 64 32 1792 2^14 8 1 half`, i.e. `Bin(1792, 2^-9)` plus `2^14`
independent root losses, each the depth-8 shadow-tree root thinned by `1/2`.
Input: NCA1's depth-8 table `Tab8.lean` (`truncTree 64 32 256 8`, scale
`D = 2^320`), parsed from its Lean source. Output (mirrors the Lean checkers
exactly, same integers):

* `TabThin.lean`  upper table of the tree law thinned by `1/2` (`checkThin`);
* `Thin.lean`     the thinning check;
* `Final.lean`    NCA1's `checkFinal` on the one-row table `[rootMarg 64 thin]`
                  at `P = 1792`, `p = 2^-9`, `g = 2^14`.

Usage: `python3 gen.py` (under a minute).
"""
import math
import re
import sys
from fractions import Fraction as Q
from pathlib import Path

sys.set_int_max_str_digits(0)
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
NCA1 = HERE.parent / 'NCA1'
sys.path.insert(0, str(NCA1))
import gen as G1  # noqa: E402

C, H, P, L = 64, 256, 1792, 64
G = 2 ** 14
PREC = 320
D = 1 << PREC
LAM_A, LAM_B = 32, 1
EARLY_D = 2 ** 9
G1.D, G1.PREC = D, PREC
TARGET = (int(sys.argv[1]), int(sys.argv[2])) if len(sys.argv) > 2 else (21, 39)


def cdiv(x, y):
    return (x + (y - 1)) // y


def trim(r):
    r = list(r)
    while r and r[-1] == 0:
        r.pop()
    return r


def load_tab8():
    src = (NCA1 / 'Tab8.lean').read_text()
    rows = re.findall(r'def t8_r(\d+) : List Nat := \[([^\]]*)\]', src)
    assert [int(m) for m, _ in rows] == list(range(C + 1))
    return [[int(x) for x in body.split(',')] if body.strip() else [] for _, body in rows]


def thin(F, al, d, Z=C, K=H):
    """Exact coefficients of `thinOut X α d K F`, the carry width, and the rounded table."""
    be = d - al
    W = [[d ** (K - r) * math.comb(r, b) * al ** b * be ** (r - b) for b in range(r + 1)]
         for r in range(K + 1)]
    c = []
    for row in F:
        cm = [0] * (K + 1)
        for r, f in enumerate(row):
            if f:
                Wr = W[r]
                for b in range(r + 1):
                    cm[b] += f * Wr[b]
        c.append(cm)
    n = len(F)
    assert n == Z + 1 and all(len(row) <= K + 1 for row in F)
    out = []
    for i in range(n):
        row = [0] * (K + 1)
        for m in range(i, n):
            v = d ** (n - 1 - m) * math.comb(m, i) * al ** i * be ** (m - i)
            cm = c[m]
            for b in range(K + 1):
                if cm[b]:
                    row[b] += cm[b] * v
        out.append(row)
    w = max(sum(r) for r in out).bit_length()
    sc = d ** (Z + K)
    return [trim([cdiv(x, sc) for x in r]) for r in out], w


def root_marg(A):
    Rm = [0] * (H + 1)
    for u, row in enumerate(A):
        sh = max(u - C, 0)
        for v, x in enumerate(row):
            Rm[v + sh] += x
    return Rm


def choose_list(n):
    out, c = [], 1
    for j in range(n):
        out.append(c)
        c = c * (P - j) // (j + 1)
    return out


def final(Rm, ap):
    cs = Rm + [0] * (H + 1 - len(Rm))
    Qv = [D] + cs[1:]
    W2 = sum(cs[j] << j for j in range(1, H + 1))
    wf = 2 * PREC + 8
    Wd = G1.Width(wf)
    fuel = G.bit_length()
    G1.H = H
    A = G1.pow_round(Wd, Qv, fuel, G)
    dp = EARLY_D
    bl = [cdiv(D * c * ap ** j * (dp - ap) ** (P - j), dp ** P)
          for j, c in enumerate(choose_list(H + 1))]
    assert sum(bl) * sum(A) < 1 << wf
    c = G1.conv_trunc(bl, A, H + 1)
    fin = sum(c[n] * max(n - L, 0) for n in range(H + 1))
    rr = max(1, cdiv(G * W2, D))
    um = G1.umNum(G1.NTAYLOR, rr, G * W2, D)
    tail = cdiv((H + 1 - L) * (dp + ap) ** P * um, 2 ** (H + 1) * dp ** P)
    tn, te = TARGET
    td = 10 ** te
    total = Q(fin, D * D) + Q(tail, D)
    print(f'gW2/D {float(Q(G * W2, D)):.4f} rr {rr} fin {float(Q(fin, D * D)):.6e} '
          f'tail {float(Q(tail, D)):.3e} total {float(total):.6e} target {tn}e-{te}')
    assert (fin + D * tail) * td <= tn * D * D
    return dict(wf=wf, fuel=fuel, rr=rr, total=total)


HEADER = '/-! {doc} Generated by `RebuildBound/Proofs/TPNum/gen.py`; do not edit. -/\n\n'


def main():
    F = load_tab8()
    Tb, w = thin(F, 1, 2)
    print('thin w', w, 'mass', float(Q(sum(map(sum, Tb)), D)))
    p = final(root_marg(Tb), 1)
    tn, te = TARGET
    out = [HEADER.format(doc='Upper table of `(truncTree 64 32 256 8).bind (thinPair half)` at scale `2^320`.'),
           'namespace RebuildBound.TPNum.Tab\n']
    for m, row in enumerate(Tb):
        out.append(f'def th_r{m} : List Nat := [{", ".join(map(str, row))}]\n')
    out.append('def th : List (List Nat) :=\n  [' + ', '.join(f'th_r{m}' for m in range(len(Tb))) + ']\n')
    out.append('end RebuildBound.TPNum.Tab')
    tab_text = '\n'.join(out) + '\n'
    thin_text = (
        'import RebuildBound.Proofs.NCA5.Checker\nimport RebuildBound.Proofs.NCA1.Tab8\n'
        'import RebuildBound.Proofs.TPNum.TabThin\n\n' +
        HEADER.format(doc='Kernel check of the thinning of the depth-8 table by `1/2`.') +
        'namespace RebuildBound.TPNum\n\n'
        '/-- Thinning of the depth-8 table by `1/2`. -/\n'
        f'theorem thin : NCA5.checkThin {w} 1 2 {C} {H} NCA1.Tab.t8 Tab.th = true := by\n'
        '  decide +kernel\n\nend RebuildBound.TPNum\n')
    final_text = (
        'import RebuildBound.Proofs.NCA5.Checker\nimport RebuildBound.Proofs.TPNum.TabThin\n\n' +
        HEADER.format(doc='Kernel check of the stop-loss series from the root-loss marginal.') +
        'namespace RebuildBound.TPNum\n\n'
        f'/-- Certified total `{float(p["total"]):.6e}`. -/\n'
        f'theorem final : NCA1.checkFinal {p["wf"]} (2 ^ {PREC}) {G1.NTAYLOR} {p["rr"]} {G1.RRED} {H} {L} '
        f'(2 ^ {G.bit_length() - 1}) {P} 1 (2 ^ 9) {LAM_A} {LAM_B} 0 {p["fuel"]} '
        f'{tn} (10 ^ {te}) 0 [NCA5.rootMarg {C} Tab.th] = true := by\n'
        '  decide +kernel\n\nend RebuildBound.TPNum\n')
    # Validate the target and generate every file before replacing any output.
    for name, text in [('TabThin.lean', tab_text), ('Thin.lean', thin_text),
                       ('Final.lean', final_text)]:
        (HERE / name).write_text(text)


if __name__ == '__main__':
    main()
